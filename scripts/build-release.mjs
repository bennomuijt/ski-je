import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const rootPath = fileURLToPath(root);
const read = path => readFileSync(new URL(path, root));
const files = directory => readdirSync(new URL(directory, root), { recursive: true, withFileTypes: true })
  .filter(entry => entry.isFile())
  .map(entry => relative(rootPath, join(entry.parentPath, entry.name)).split(sep).join('/'))
  .sort();
const hash = (data, encoding) => createHash('sha256').update(data).digest(encoding);
const { version } = JSON.parse(read('package.json'));
const generatedIcons = ['icons/icon-192-v455.png', 'icons/icon-512-v455.png'];
const assets = files('public').filter(path => !['sw.js', '_headers', ...generatedIcons].includes(path.slice(7)));

const stampHtml = (html, build) => html
  .replace(/<meta name="skije-build" content="[^"]*">/, `<meta name="skije-build" content="${build}">`)
  .replace(/class="app-version">v[\d.]+</, `class="app-version">v${version}<`)
  .replace(/SKI-je v[\d.]+-Cloudflare-test/, `SKI-je v${version}-Cloudflare-test`);
const stampWorker = (worker, build, integrity) => worker
  .replace(/^const BUILD = .*;$/m, `const BUILD = ${JSON.stringify(build)};`)
  .replace(/^const CORE = .*;$/m, `const CORE = ${JSON.stringify(integrity)};`);

const html = read('public/index.html').toString();
const worker = read('public/sw.js').toString();
const inputs = new Map(assets.map(path => [path, read(path)]));
inputs.set('public/index.html', stampHtml(html, ''));
inputs.set('public/sw.js', stampWorker(worker, '', {}));
for (const path of [...files('src').filter(path => path !== 'src/release.js'),
  'public/_headers', 'wrangler.jsonc', 'scripts/build-icons.mjs', 'scripts/build-release.mjs']) {
  inputs.set(path, read(path));
}
const fingerprint = [...inputs].map(([path, content]) => [path, hash(content, 'hex')]);
const build = hash(JSON.stringify([version, fingerprint]), 'hex').slice(0, 24);
inputs.set('public/index.html', stampHtml(html, build));
const integrity = Object.fromEntries(assets.map(path => [
  './' + path.slice(7), 'sha256-' + hash(inputs.get(path), 'base64')
]));
// Icons are regenerated by sharp and can differ across platforms.
for (const path of generatedIcons) integrity['./' + path] = '';
const outputs = {
  'public/index.html': stampHtml(html, build),
  'public/sw.js': stampWorker(worker, build, integrity),
  'src/release.js': `// Generated by npm run build:release.\nexport const release = ${JSON.stringify({ version: version + '-cf', build })};\n`
};
for (const [path, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (read(path).toString() !== content) {
      console.error(`${path} has stale release metadata. Run npm run build:release.`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(new URL(path, root), content);
  }
}
